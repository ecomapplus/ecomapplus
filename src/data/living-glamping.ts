import type { Community } from "./communities";

type Stay = {
  slug: string;
  name: string;
  location: string;
  region: string;
  acres: number | null;
  acresLabel: string;
  hosts: string;
  summary: string;
  website: string;
};

function glamping(row: Stay): Community {
  return {
    slug: row.slug,
    name: row.name,
    location: row.location,
    region: row.region,
    country: "United States",
    foundedYear: 2024,
    foundedLabel: "The year the farm began is not published. The stay is what is listed.",
    members: 0,
    membersLabel: `${row.hosts}. No resident community.`,
    acres: row.acres,
    acresLabel: row.acresLabel,
    legalStructure: "Private farm. You book a night. There is no village to join.",
    legalCategory: "Glamping farm stay",
    stillActive: true,
    images: [],
    summary: row.summary,
    businessModel: "A booked farm stay. Not membership.",
    foundingProcess: "The hosts farm the land and rent a bed.",
    governance: "The hosts.",
    website: row.website,
    timeline: [{ year: "Present", event: "Book the stay. The farm is not taking members." }],
  };
}

